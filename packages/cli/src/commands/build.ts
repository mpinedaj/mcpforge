import { promises as fs } from "node:fs";
import { resolve } from "node:path";
import type { Command } from "commander";
import { writeManifest } from "@mcpforge/core";
import { loadRuntimePaths, log, writeJson } from "./shared";

export function registerBuildCommand(program: Command): void {
  program
    .command("build")
    .description("Create a deployable folder with the manifest, config and Dockerfile")
    .option("-m, --manifest <path>", "path to the tool manifest")
    .option("-c, --config <path>", "path to mcpforge.config.json")
    .option("-o, --out <dir>", "output directory", "mcpforge-build")
    .option("--base-url <url>", "override the upstream base URL")
    .action(
      async (options: {
        manifest?: string;
        config?: string;
        out: string;
        baseUrl?: string;
      }) => {
        const { config, manifest } = await loadRuntimePaths(options);
        const outputDir = resolve(process.cwd(), options.out);
        await fs.mkdir(outputDir, { recursive: true });

        const manifestPath = resolve(outputDir, "mcpforge.json");
        const configPath = resolve(outputDir, "mcpforge.config.json");

        await writeManifest(manifestPath, manifest);
        await writeJson(configPath, { ...config, manifest: "mcpforge.json" });

        const port = config.http.port;
        const dockerfile = buildDockerfile(port);
        await fs.writeFile(resolve(outputDir, "Dockerfile"), dockerfile, "utf8");
        await fs.writeFile(resolve(outputDir, "README.md"), buildReadme(manifest.title ?? config.name, port), "utf8");
        await fs.writeFile(resolve(outputDir, ".dockerignore"), "node_modules\n.git\n.mcpforge\n", "utf8");

        log(`build written to ${outputDir}`);
        log(`next: docker build -t ${config.name} ${options.out}`);
        log(`      docker run --rm -p ${port}:${port} -e MCPFORGE_AUTH_TOKEN=... ${config.name}`);
      },
    );
}

function buildDockerfile(port: number): string {
  return `# Generated by MCPForge. Requires the @x123martin/mcpforge-cli package to be published.
FROM node:24-alpine
WORKDIR /app
RUN npm install -g @x123martin/mcpforge-cli@latest
COPY mcpforge.json mcpforge.config.json ./
ENV MCPFORGE_READ_ONLY=true
EXPOSE ${port}
CMD ["mcpforge", "serve", "--http", "--host", "0.0.0.0"]
`;
}

function buildReadme(name: string, port: number): string {
  return `# ${name} · MCPForge build

This folder contains a ready-to-deploy MCP server.

## Run with Docker

\`\`\`bash
docker build -t ${name} .
docker run --rm -p ${port}:${port} -e MCPFORGE_AUTH_TOKEN=your-token ${name}
\`\`\`

- MCP endpoint: \`http://localhost:${port}/mcp\`
- Inspector: \`http://localhost:${port}\`
- Health: \`http://localhost:${port}/health\`

## Security defaults

- Read-only mode is enabled.
- Write tools are hidden and blocked.
- Audit logs are written to \`.mcpforge/audit.log\`.

Override with environment variables: \`MCPFORGE_READ_ONLY=false\`, \`MCPFORGE_RATE_LIMIT=120\`,
\`MCPFORGE_BASE_URL=https://api.example.com\`.
`;
}
